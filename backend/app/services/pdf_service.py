import os
import io
import logging
from datetime import datetime
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image as RLImage, KeepTogether, HRFlowable
)
from reportlab.pdfgen import canvas
from app.services.cloudinary_service import storage_service

logger = logging.getLogger(__name__)

class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            super().showPage()
        super().save()

    def draw_page_number(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))
        
        # Header banner line
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.5)
        self.line(40, 11 * 72 - 35, 8.5 * 72 - 40, 11 * 72 - 35)
        self.drawString(40, 11 * 72 - 30, "VAULTORY - Digital Ownership & Warranty Evidence Report")
        
        # Footer
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(8.5 * 72 - 40, 30, page_text)
        self.drawString(40, 30, "Confidential & Verified Evidence Document | Generated by Vaultory")
        self.line(40, 42, 8.5 * 72 - 40, 42)
        self.restoreState()


class PDFEvidenceService:
    def generate_product_evidence_pdf(self, product, user) -> bytes:
        """
        Generates a comprehensive PDF report containing:
        - Product specifications & purchase information
        - Warranty details & remaining validity
        - Condition photographs (original & current)
        - Purchase receipt documentation
        - Repair & service records table
        """
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=40,
            leftMargin=40,
            topMargin=50,
            bottomMargin=55
        )

        styles = getSampleStyleSheet()
        
        # Custom Typography Styles
        title_style = ParagraphStyle(
            'DocTitle',
            parent=styles['Heading1'],
            fontName='Helvetica-Bold',
            fontSize=20,
            leading=24,
            textColor=colors.HexColor("#0f172a")
        )
        subtitle_style = ParagraphStyle(
            'DocSubtitle',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=9,
            leading=13,
            textColor=colors.HexColor("#64748b")
        )
        section_heading = ParagraphStyle(
            'SectionHeading',
            parent=styles['Heading2'],
            fontName='Helvetica-Bold',
            fontSize=12,
            leading=16,
            textColor=colors.HexColor("#1e293b"),
            spaceBefore=14,
            spaceAfter=6
        )
        cell_label = ParagraphStyle(
            'CellLabel',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=8.5,
            leading=11,
            textColor=colors.HexColor("#475569")
        )
        cell_val = ParagraphStyle(
            'CellVal',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=8.5,
            leading=11,
            textColor=colors.HexColor("#0f172a")
        )

        elements = []

        # 1. Header & Certificate Metadata
        elements.append(Paragraph("DIGITAL PRODUCT OWNERSHIP & WARRANTY REPORT", title_style))
        report_id = f"VLT-{product.id:06d}-{datetime.now().strftime('%Y%m%d')}"
        gen_time = datetime.now().strftime("%B %d, %Y at %H:%M UTC")
        elements.append(Paragraph(f"Evidence Certificate ID: <b>{report_id}</b> | Generated on {gen_time}", subtitle_style))
        elements.append(Paragraph(f"Owner: <b>{user.full_name or user.email}</b> ({user.email})", subtitle_style))
        elements.append(Spacer(1, 10))
        elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#2563eb"), spaceBefore=2, spaceAfter=12))

        # 2. Product Information
        elements.append(Paragraph("1. PRODUCT SPECIFICATIONS & PURCHASE DETAILS", section_heading))
        
        prod_data = [
            [
                Paragraph("Product Name:", cell_label), Paragraph(product.name or "N/A", cell_val),
                Paragraph("Brand / Make:", cell_label), Paragraph(product.brand or "N/A", cell_val)
            ],
            [
                Paragraph("Model Number:", cell_label), Paragraph(product.model_number or "N/A", cell_val),
                Paragraph("Serial Number:", cell_label), Paragraph(product.serial_number or "N/A", cell_val)
            ],
            [
                Paragraph("Category:", cell_label), Paragraph(product.category or "Electronics", cell_val),
                Paragraph("Retailer / Store:", cell_label), Paragraph(product.retailer or "N/A", cell_val)
            ],
            [
                Paragraph("Purchase Date:", cell_label), Paragraph(str(product.purchase_date or "N/A"), cell_val),
                Paragraph("Purchase Price:", cell_label), Paragraph(f"{product.currency or 'USD'} {product.purchase_price:.2f}" if product.purchase_price else "N/A", cell_val)
            ]
        ]
        
        t_prod = Table(prod_data, colWidths=[105, 160, 105, 162])
        t_prod.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ]))
        elements.append(t_prod)
        elements.append(Spacer(1, 10))

        # 3. Warranty Status
        elements.append(Paragraph("2. WARRANTY & COVERAGE DETAILS", section_heading))
        if product.warranty:
            w = product.warranty
            today = datetime.now().date()
            rem_days = (w.end_date - today).days if w.end_date else 0
            status_text = "ACTIVE" if rem_days > 30 else ("EXPIRING SOON" if rem_days >= 0 else "EXPIRED")
            status_color = "#16a34a" if status_text == "ACTIVE" else ("#ea580c" if status_text == "EXPIRING SOON" else "#dc2626")

            w_data = [
                [
                    Paragraph("Warranty Type:", cell_label), Paragraph(w.warranty_type or "Manufacturer", cell_val),
                    Paragraph("Current Status:", cell_label), Paragraph(f"<font color='{status_color}'><b>{status_text}</b> ({rem_days} days remaining)</font>", cell_val)
                ],
                [
                    Paragraph("Start Date:", cell_label), Paragraph(str(w.start_date), cell_val),
                    Paragraph("End Date:", cell_label), Paragraph(str(w.end_date), cell_val)
                ],
                [
                    Paragraph("Duration:", cell_label), Paragraph(f"{w.duration_months} Months", cell_val),
                    Paragraph("Provider Contact:", cell_label), Paragraph(w.provider_contact or "N/A", cell_val)
                ],
                [
                    Paragraph("Coverage Notes:", cell_label), Paragraph(w.coverage_details or w.notes or "Standard hardware & manufacturer defects coverage.", cell_val),
                    Paragraph("", cell_label), Paragraph("", cell_val)
                ]
            ]
            t_w = Table(w_data, colWidths=[105, 160, 105, 162])
            t_w.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
                ('SPAN', (1, 3), (3, 3)),
                ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ('TOPPADDING', (0, 0), (-1, -1), 5),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
            ]))
            elements.append(t_w)
        else:
            elements.append(Paragraph("No active warranty record attached to this product.", cell_val))

        elements.append(Spacer(1, 10))

        # 4. Condition Photographs (Original & Current)
        elements.append(Paragraph("3. PRODUCT CONDITION RECORDS & PHOTOGRAPHS", section_heading))
        
        orig_photos = [p for p in product.condition_photos if p.photo_type == "original"]
        curr_photos = [p for p in product.condition_photos if p.photo_type == "current"]

        photo_cells = []
        
        # Original Photo
        if orig_photos:
            p_orig = orig_photos[0]
            local_path = storage_service.get_local_path_from_url(p_orig.photo_url)
            if local_path and os.path.exists(local_path):
                try:
                    img_flow = RLImage(local_path, width=220, height=150)
                    photo_cells.append([
                        Paragraph("<b>Original Condition Photo</b>", cell_label),
                        img_flow,
                        Paragraph(f"Captured: {p_orig.taken_at.strftime('%Y-%m-%d') if p_orig.taken_at else 'At Registration'}<br/>{p_orig.caption or ''}", subtitle_style)
                    ])
                except Exception as e:
                    logger.warning(f"Failed to embed original photo: {e}")
        
        # Current Photo
        if curr_photos:
            p_curr = curr_photos[0]
            local_path = storage_service.get_local_path_from_url(p_curr.photo_url)
            if local_path and os.path.exists(local_path):
                try:
                    img_flow = RLImage(local_path, width=220, height=150)
                    photo_cells.append([
                        Paragraph("<b>Latest Verified Condition</b>", cell_label),
                        img_flow,
                        Paragraph(f"Updated: {p_curr.taken_at.strftime('%Y-%m-%d') if p_curr.taken_at else 'Recent'}<br/>{p_curr.caption or ''}", subtitle_style)
                    ])
                except Exception as e:
                    logger.warning(f"Failed to embed current photo: {e}")

        if len(photo_cells) == 2:
            table_photos = Table([
                [photo_cells[0][0], photo_cells[1][0]],
                [photo_cells[0][1], photo_cells[1][1]],
                [photo_cells[0][2], photo_cells[1][2]]
            ], colWidths=[260, 260])
            table_photos.setStyle(TableStyle([
                ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
                ('VALIGN', (0, 0), (-1, -1), 'TOP'),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ]))
            elements.append(table_photos)
        elif len(photo_cells) == 1:
            table_photos = Table([
                [photo_cells[0][0]],
                [photo_cells[0][1]],
                [photo_cells[0][2]]
            ], colWidths=[520])
            elements.append(table_photos)
        else:
            elements.append(Paragraph("No physical condition photographs uploaded yet.", subtitle_style))

        elements.append(Spacer(1, 10))

        # 5. Purchase Receipt Document
        elements.append(Paragraph("4. PURCHASE RECEIPT EVIDENCE", section_heading))
        receipt_path = storage_service.get_local_path_from_url(product.receipt_url) if product.receipt_url else None
        if receipt_path and os.path.exists(receipt_path):
            ext = os.path.splitext(receipt_path)[1].lower()
            if ext in ['.jpg', '.jpeg', '.png', '.webp']:
                try:
                    r_img = RLImage(receipt_path, width=320, height=200)
                    elements.append(Table([
                        [Paragraph(f"<b>Uploaded Receipt Document:</b> {product.receipt_filename or 'receipt.jpg'}", cell_val)],
                        [r_img]
                    ], colWidths=[520]))
                except Exception as e:
                    elements.append(Paragraph(f"Receipt document attached: {product.receipt_filename} ({product.receipt_url})", cell_val))
            else:
                elements.append(Paragraph(f"Receipt document (PDF/Document): {product.receipt_filename or 'receipt.pdf'} is archived in digital ownership record.", cell_val))
        else:
            elements.append(Paragraph(f"Receipt file link: {product.receipt_url or 'Manual Entry / No file uploaded'}", cell_val))

        elements.append(Spacer(1, 10))

        # 6. Repair & Service History
        elements.append(Paragraph("5. REPAIR & MAINTENANCE HISTORY", section_heading))
        if product.repairs:
            r_headers = [
                Paragraph("<b>Date</b>", cell_label),
                Paragraph("<b>Service Center</b>", cell_label),
                Paragraph("<b>Description</b>", cell_label),
                Paragraph("<b>Cost</b>", cell_label),
                Paragraph("<b>Warranty Covered</b>", cell_label),
                Paragraph("<b>Status</b>", cell_label),
            ]
            r_rows = [r_headers]
            total_cost = 0.0
            for rep in product.repairs:
                total_cost += (rep.cost or 0.0)
                r_rows.append([
                    Paragraph(str(rep.repair_date), cell_val),
                    Paragraph(rep.service_center, cell_val),
                    Paragraph(rep.description, cell_val),
                    Paragraph(f"${rep.cost:.2f}", cell_val),
                    Paragraph("Yes" if rep.warranty_covered else "No", cell_val),
                    Paragraph(rep.status, cell_val)
                ])
            
            # Total summary row
            r_rows.append([
                Paragraph("<b>Total Repairs</b>", cell_label),
                Paragraph(f"<b>{len(product.repairs)} record(s)</b>", cell_label),
                Paragraph("", cell_label),
                Paragraph(f"<b>${total_cost:.2f}</b>", cell_label),
                Paragraph("", cell_label),
                Paragraph("", cell_label)
            ])

            t_rep = Table(r_rows, colWidths=[65, 105, 180, 55, 65, 60])
            t_rep.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ('TOPPADDING', (0, 0), (-1, -1), 4),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ]))
            elements.append(t_rep)
        else:
            elements.append(Paragraph("No repairs or maintenance records have been logged for this product.", cell_val))

        elements.append(Spacer(1, 15))

        # 7. Verification Notice
        disclaimer = (
            "<b>Legal & Verification Notice:</b> This digital ownership and warranty evidence document has been compiled and validated "
            "using the Vaultory Digital Asset Management System. All receipts, timestamps, and condition photographs represent the chronological "
            "ownership history recorded by the authenticated owner. For verification or warranty claim processing, submit this document "
            "directly to the authorized service center or manufacturer."
        )
        elements.append(Paragraph(disclaimer, subtitle_style))

        # Build PDF
        doc.build(elements, canvasmaker=NumberedCanvas)
        buffer.seek(0)
        return buffer.getvalue()

pdf_service = PDFEvidenceService()

